A organização analisa o pedido para confirmar o alinhamento com o propósito e as regras, a autenticidade do cadastro e a conduta compatível com o ambiente. A análise não discrimina por profissão, cargo, empresa, situação de emprego, gênero, idade, crença ou origem.

