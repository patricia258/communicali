## 1. Quem é quem

Convidado: pessoa que chega a uma atividade pela indicação de um Membro. O convite vale para uma edição, depende de inscrição, confirmação e vaga, e não cria a identidade de Membro.

Visitante: pessoa que participa por interesse próprio, para conhecer a comunidade, sem depender de convite.

Membro: pessoa com adesão aprovada pela organização. A identidade de Membro é gratuita e continua gratuita.

Conector e Embaixador: reconhecimentos de quem contribui com a comunidade, com critérios e responsabilidades próprios. Nunca são faixas de preço.

Parceiro: profissional ou empresa que contribui com programação, espaço, materiais ou experiência. Não é o mesmo que convidado.

Convidado e Visitante são portas de entrada. A trilha de pertencimento começa em Membro.

## 2. Conhecer antes de aderir

Você pode viver até 2 visitas abertas e gratuitas antes de fazer parte da comunidade, presenciais ou online. Convidado e Visitante somam no mesmo contador: 1 como Convidado e 1 como Visitante são 2, assim como 2 como Convidado ou 2 como Visitante.

Só conta a presença confirmada no check-in, ou seja, quando a pessoa esteve no encontro. Inscrição, lista da recepção, reserva, cancelamento e ausência não contam.

Depois de 2 presenças, nova participação em atividades abertas e gratuitas exige adesão aprovada como Membro. Atividades pagas, workshops, imersões e experiências especiais têm regras próprias e, salvo aviso da edição, não gastam esse limite.

## 3. Como se tornar Membro

Ir ao encontro não torna ninguém Membro automaticamente. Depois da primeira presença validada, você já pode pedir a adesão. Não é preciso usar as duas experiências.

O pedido exige: ter ao menos 1 presença validada, manifestar o interesse em ser Membro, preencher o cadastro mínimo e aceitar estes termos, as Regras de participação e a Política de privacidade. Autorizações de imagem, marketing e aparecer no diretório são escolhas separadas e não são condição para ser Membro.

A organização analisa o pedido para confirmar o alinhamento com o propósito e as regras, a autenticidade do cadastro e a conduta compatível com o ambiente. A análise não discrimina por profissão, cargo, empresa, situação de emprego, gênero, idade, crença ou origem.

O retorno pode ser: aprovado, ajustes necessários ou não aprovado, sempre com o motivo. Nenhum cartão ou assinatura é pedido para a adesão.

## 4. Meu passaporte

Convidados e Visitantes usam apenas o que a edição pede: inscrição, confirmação, check-in, votação, dinâmica e formulários públicos. O Meu passaporte completo, a Rede, as missões e as milhas abrem depois da adesão aprovada.

O primeiro crachá reutilizável de Membro e o primeiro selo de presença são gratuitos, entregues após cadastro e check-in elegíveis e sujeitos à disponibilidade informada. Reposição de crachá é cobrada à parte, com o valor informado antes do pedido.

