## 1. O que esperamos de quem participa

Interação de verdade. Networking só acontece com relacionamento e intencionalidade. Ninguém é obrigado a falar todo dia, mas este espaço é para quem quer contribuir, colaborar e trocar.

Respeito às pessoas. Todos são bem-vindos: profissionais de RH e administrativos, líderes e especialistas de qualquer área, em qualquer momento da carreira, do estágio à transição profissional.

Debate com cuidado. Discordar é bem-vindo e faz parte da conversa. A crítica vai para a ideia, nunca para a pessoa.

## 2. O que é liberado

Divulgar vagas reais, compartilhar contatos, abrir discussões e divulgar seus próprios serviços e trabalhos.

Pedir ajuda, indicação e opinião.

Falar de assuntos difíceis, inclusive quando as opiniões não batem.

## 3. O que não é permitido

Assédio, ameaça, humilhação, perseguição ou exposição de qualquer pessoa.

Discriminação ou ofensa por raça, cor, etnia, religião, origem, gênero, orientação sexual, idade, deficiência ou condição social.

Golpes, pirâmides, promessas enganosas, vagas falsas ou cobrança de candidatos para concorrer a uma vaga.

Conteúdo sexual, violento, ilegal ou notícia sabidamente falsa.

Repetir a mesma divulgação em sequência, ou chamar membros no privado para vender depois de a pessoa pedir que você pare.

Campanha político-partidária ou pregação com a intenção de convencer o grupo. Opinião é bem-vinda, e ninguém é excluído por sua convicção política ou religiosa.

Falar em nome da ComuniCALI ou da CALI RH sem autorização.

## 4. O que pode e o que não pode sair da comunidade

Pode sair: o que você aprendeu, as ideias discutidas e suas próprias reflexões, desde que ninguém seja identificado sem autorização.

Não pode sair: prints, áudios, gravações ou trechos de conversa de outras pessoas, sem autorização delas.

Não pode sair: nomes, telefones, e-mails ou a lista de participantes. Não é permitido copiar contatos para listas de marketing, outros grupos ou bases de dados, nem adicionar alguém a outro grupo sem permissão.

Não pode sair: histórias pessoais, situações de empresas ou informações confidenciais contadas aqui. O que se conta na roda fica na roda.

Se você precisar usar uma conversa para se defender ou denunciar algo grave, procure a organização. A proteção de quem foi vítima sempre vem antes.

## 5. Encontros, lives e imagem

Fotos e gravações da organização são avisadas antes. Só publicamos imagens de quem autorizou. A autorização de uso de imagem é separada do aceite destas regras e é voluntária: quem não autoriza participa do mesmo jeito.

Antes de postar foto de outro participante, peça permissão à pessoa. Crianças só aparecem com autorização de quem é responsável por elas.

Gravar uma live ou uma conversa só é permitido quando a organização avisa que a gravação está autorizada.

## 6. O que acontece quando uma regra é quebrada

Primeira situação: orientação em particular, para esclarecer e corrigir.

Repetição: advertência formal e, se preciso, retirada da mensagem.

Nova repetição: remoção da comunidade.

Remoção imediata e sem aviso prévio, sem possibilidade de retorno: assédio, discriminação, ameaça, golpe, vaga falsa, conteúdo ilegal, divulgação de prints ou dados de membros com intenção de expor alguém, e venda ou uso comercial da lista de membros.

A remoção vale para todos os canais e encontros. Milhas, categoria e crachá deixam de valer. Quando a situação envolver crime, a organização pode acionar as autoridades.

