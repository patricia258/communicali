## 8. Conector e Embaixador

Conector e Embaixador são reconhecimentos de quem contribui com a comunidade. Conectores acolhem pessoas e facilitam apresentações, e não moderam. Embaixadores só apoiam a moderação quando a organização autoriza expressamente, caso a caso. Nenhum dos dois fala em nome da organização, promete benefícios ou contrata em nome dela.

